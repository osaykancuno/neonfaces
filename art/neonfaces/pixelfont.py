def text_width(text: str, s: int) -> int:
    return len(text) * 6 * s - s


def draw_text(d, text: str, x: int, y: int, s: int, color) -> None:
    """Draw `text` with its top-left corner at (x, y), each font pixel an s×s block."""
    for ch in text:
        for r, row in enumerate(FONT[ch]):
            for c, bit in enumerate(row):
                if bit == "1":
                    d.rectangle([x + c * s, y + r * s, x + c * s + s - 1, y + r * s + s - 1], fill=color)
        x += 6 * s


def draw_centered(d, text: str, cx: int, y: int, s: int, color) -> None:
    draw_text(d, text, cx - text_width(text, s) // 2, y, s, color)
