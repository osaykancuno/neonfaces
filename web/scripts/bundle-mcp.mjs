// Copies What I see's two pure modules (src/analysis.js, src/guard.js) into the MCP kit (public/neonfaces-mcp.mjs),
// between its BUNDLE markers, so the kit stays one file with no dependencies and says exactly what the site says.
// Runs before every build (npm "prebuild"); `node scripts/bundle-mcp.mjs --check` fails if the kit is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const at = (p) => fileURLToPath(new URL(`../${p}`, import.meta.url));
const KIT = at("public/neonfaces-mcp.mjs");
const BEGIN = "// ==== BEGIN bundled What I see (generated by scripts/bundle-mcp.mjs from src/analysis.js and src/guard.js: edit those) ====";
const END = "// ==== END bundled What I see ====";

/** One module as a namespace object: its source without `export`, wrapped in a function that returns its exports. */
function wrap(name, file) {
  const src = readFileSync(at(file), "utf8").replace(/\r\n/g, "\n");
  if (/^\s*import\s/m.test(src)) throw new Error(`${file} imports something: the kit can only bundle pure modules`);
  const names = [...src.matchAll(/^export\s+(?:async\s+)?(?:function|const|let)\s+([A-Za-z0-9_$]+)/gm)].map((m) => m[1]);
  const body = src.replace(/^export\s+/gm, "");
  return `const ${name} = (() => {\n${body}\nreturn { ${names.join(", ")} };\n})();`;
}

export function bundled() {
  return [BEGIN, wrap("ANALYSIS", "src/analysis.js"), wrap("GUARD", "src/guard.js"), END].join("\n");
}

const kit = readFileSync(KIT, "utf8");
const a = kit.indexOf(BEGIN);
const b = kit.indexOf(END);
if (a < 0 || b < a) throw new Error("the kit has no BUNDLE markers");
const next = kit.slice(0, a) + bundled() + kit.slice(b + END.length);
if (process.argv.includes("--check")) {
  if (next !== kit) {
    console.error("public/neonfaces-mcp.mjs is out of date: run node scripts/bundle-mcp.mjs");
    process.exit(1);
  }
  console.log("MCP kit bundle up to date");
} else if (next !== kit) {
  writeFileSync(KIT, next);
  console.log("MCP kit bundle written");
}
