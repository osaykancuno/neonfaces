// Builds the downloadable MCP kit (public/neonfaces-mcp.mjs): one file, no dependencies, Node 18+, made of What I
// see's pure modules (src/analysis.js, src/guard.js), the server core (mcp/core.mjs, also served by the site's Worker at
// neonfaces.xyz/mcp) and the stdio entry (mcp/stdio.mjs). Runs before every build (npm "prebuild");
// `node scripts/bundle-mcp.mjs --check` fails if the kit is out of date. Never edit the kit itself.
import { readFileSync, writeFileSync, renameSync } from "node:fs";
import { fileURLToPath } from "node:url";

const at = (p) => fileURLToPath(new URL(`../${p}`, import.meta.url));
const KIT = at("public/neonfaces-mcp.mjs");
const read = (f) => readFileSync(at(f), "utf8").replace(/\r\n/g, "\n");

/** A module as a namespace object: its source without imports and `export`, inside a function returning its exports. */
function wrap(name, file, allowed = []) {
  let src = read(file);
  const imports = [...src.matchAll(/^import\s.*?from\s+"([^"]+)";\n/gm)];
  for (const m of imports) if (!allowed.includes(m[1])) throw new Error(`${file} imports ${m[1]}: the kit can only bundle what it lists`);
  src = src.replace(/^import\s.*?from\s+"[^"]+";\n/gm, "");
  const names = [...src.matchAll(/^export\s+(?:async\s+)?(?:function|const|let)\s+([A-Za-z0-9_$]+)/gm)].map((m) => m[1]);
  return `const ${name} = (() => {\n${src.replace(/^export\s+/gm, "")}\nreturn { ${names.join(", ")} };\n})();`;
}

export function kit() {
  const stdio = read("mcp/stdio.mjs").replace(/^import \{ createServer \} from "\.\/core\.mjs";\n/m, "");
  const [head, body] = [stdio.slice(0, stdio.indexOf("const server")), stdio.slice(stdio.indexOf("const server"))];
  return [
    "#!/usr/bin/env node",
    "// NEONFACES: talk to your Face. A Model Context Protocol server for AI assistants (Claude Desktop, and any MCP client).",
    "// One file, no dependencies, Node 18+. It only READS the chain; for anything that changes a Face it returns a link to",
    "// the Face page, where the holder confirms in their own wallet. It never sees or asks for keys. No download needed:",
    "// the same server runs at https://neonfaces.xyz/mcp (add that address to an assistant that takes remote MCP servers).",
    "//",
    "// Claude Desktop > Settings > Developer > Edit config, add:",
    '//   "mcpServers": { "neonfaces": { "command": "node", "args": ["C:/path/to/neonfaces-mcp.mjs"] } }',
    "//",
    "// GENERATED by web/scripts/bundle-mcp.mjs from web/mcp/core.mjs, web/mcp/stdio.mjs, web/src/analysis.js and",
    "// web/src/guard.js (github.com/osaykancuno/neonfaces). Edit those, never this file.",
    head.trim(),
    "",
    wrap("ANALYSIS", "src/analysis.js"),
    "",
    wrap("GUARD", "src/guard.js"),
    "",
    wrap("CORE", "mcp/core.mjs", ["../src/analysis.js", "../src/guard.js"]),
    "const { createServer } = CORE;",
    "",
    body.trim(),
    "",
  ].join("\n");
}

const next = kit();
let now = "";
try {
  now = readFileSync(KIT, "utf8");
} catch {}
if (process.argv.includes("--check")) {
  if (next !== now) {
    console.error("public/neonfaces-mcp.mjs is out of date: run node scripts/bundle-mcp.mjs");
    process.exit(1);
  }
  console.log("MCP kit up to date");
} else if (next !== now) {
  writeFileSync(KIT + ".tmp", next); // written next to it first: a full disk must never leave the kit empty
  renameSync(KIT + ".tmp", KIT);
  console.log("MCP kit written");
}
